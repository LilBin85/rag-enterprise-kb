"""统一会话存储与任务编排的稳定应用端口。"""

from __future__ import annotations

from typing import Any, Protocol

from rag_kb.domain.identity import AuthContext


class ConversationRepositoryError(RuntimeError):
    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


class ConversationRepositoryPort(Protocol):
    def create(self, *, auth: AuthContext, title: str | None = None) -> Any: ...
    def list_owned(self, **kwargs: Any) -> Any: ...
    def get_owned(self, **kwargs: Any) -> Any: ...
    def messages_owned(self, **kwargs: Any) -> Any: ...
    def context_messages(self, **kwargs: Any) -> Any: ...
    def begin_new_turn(self, **kwargs: Any) -> Any: ...
    def append_clarification_reply(self, **kwargs: Any) -> Any: ...
    def settle_answer(self, **kwargs: Any) -> Any: ...
    def fail_fast_answer(self, **kwargs: Any) -> bool: ...
    def request_delete(self, **kwargs: Any) -> Any: ...
    def active_turn(self, **kwargs: Any) -> Any: ...
    def get_turn(self, **kwargs: Any) -> Any: ...
    def latest_assistant_message(self, **kwargs: Any) -> Any: ...
    def revalidated_citations(self, **kwargs: Any) -> Any: ...
    def revalidated_artifacts(self, **kwargs: Any) -> Any: ...


class ConversationTaskRepositoryPort(Protocol):
    def create_task_in_session(self, session: Any, **kwargs: Any) -> Any: ...
    def get_task(self, **kwargs: Any) -> Any: ...
    def enqueue_user_resume_command(self, **kwargs: Any) -> Any: ...
    def enqueue_user_resume_command_in_session(self, session: Any, **kwargs: Any) -> Any: ...
